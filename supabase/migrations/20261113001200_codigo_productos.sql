alter table public.products
  add column code integer generated by default as identity (start with 1);

-- los que ya existen: numerados en el orden en que se ven
with orden as (
  select id, row_number() over (order by sort_order, created_at) as n
  from public.products
)
update public.products p set code = orden.n from orden where orden.id = p.id;
select setval(
  pg_get_serial_sequence('public.products', 'code'),
  greatest((select max(code) from public.products), 1),
  (select count(*) > 0 from public.products)
);

alter table public.products alter column code set not null;
alter table public.products add constraint products_code_key unique (code);

-- el número no se cambia nunca (ni desde el panel ni por la API)
create function private.codigo_fijo()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.code is distinct from old.code then
    raise exception 'El código de un producto no se puede cambiar' using errcode = '22023';
  end if;
  return new;
end;
$$;

create trigger products_codigo_fijo
  before update of code on public.products
  for each row execute function private.codigo_fijo();

-- importación: las filas con código se buscan por número
create or replace function public.admin_import_catalog(payload jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  item         jsonb;
  variant      jsonb;
  cat_id       uuid;
  prod_id      uuid;
  creados      integer := 0;
  actualizados integer := 0;
  variantes    integer := 0;
  orden        integer;
  nuevo_slug   text;
  sufijo       integer;
begin
  if not private.is_admin() then
    raise exception 'No autorizado' using errcode = '42501';
  end if;

  if jsonb_typeof(payload -> 'products') is distinct from 'array' then
    raise exception 'Formato inválido: falta la lista "products"' using errcode = '22023';
  end if;

  if jsonb_array_length(payload -> 'products') > 500 then
    raise exception 'Demasiados productos en una sola importación (máx. 500)' using errcode = '22023';
  end if;

  -- primero las filas con código (así, si a uno le cambiaron el nombre, una
  -- fila nueva con el nombre viejo no se confunde con él)
  for item in
    select e.value from jsonb_array_elements(payload -> 'products') with ordinality e(value, n)
    order by (e.value ->> 'code') is null, e.n
  loop
    cat_id := null;
    if coalesce(item ->> 'category_slug', '') <> '' then
      select c.id into cat_id from public.categories c where c.slug = item ->> 'category_slug';
      if cat_id is null then
        raise exception 'Fila de "%": la categoría "%" no existe', item ->> 'name', item ->> 'category_slug'
          using errcode = '22023';
      end if;
    end if;

    prod_id := null;
    if coalesce(item ->> 'code', '') <> '' then
      -- fila de la planilla descargada: se busca por su número (no cambia
      -- aunque le cambien el nombre)
      if (item ->> 'code') !~ '^[0-9]{1,9}$' then
        raise exception 'Fila de "%": el código "%" no es válido (no lo cambies)', item ->> 'name', item ->> 'code'
          using errcode = '22023';
      end if;
      select p.id into prod_id from public.products p where p.code = (item ->> 'code')::integer;
      if prod_id is null then
        raise exception 'Fila de "%": no hay ningún producto con el código %', item ->> 'name', item ->> 'code'
          using errcode = '22023';
      end if;
    else
      -- fila sin código: si ya existe uno que HOY se llama igual, es ese
      select p.id into prod_id from public.products p
        where lower(btrim(p.name)) = lower(btrim(item ->> 'name'))
        order by p.code limit 1;
    end if;

    if prod_id is null then
      -- identificador interno libre (si "lemon-pie" ya existe: "lemon-pie-2")
      nuevo_slug := item ->> 'slug';
      sufijo := 1;
      while exists (select 1 from public.products p where p.slug = nuevo_slug) loop
        sufijo := sufijo + 1;
        nuevo_slug := left(item ->> 'slug', 110) || '-' || sufijo;
      end loop;
      select coalesce(max(p.sort_order), 0) + 1 into orden from public.products p;
      insert into public.products (slug, name, category_id, short_description, is_published, sort_order)
      values (
        nuevo_slug,
        item ->> 'name',
        cat_id,
        nullif(item ->> 'short_description', ''),
        coalesce((item ->> 'is_published')::boolean, true),
        orden
      )
      returning id into prod_id;
      creados := creados + 1;
    else
      update public.products p
         set name              = item ->> 'name',
             category_id       = coalesce(cat_id, p.category_id),
             short_description = coalesce(nullif(item ->> 'short_description', ''), p.short_description),
             is_published      = coalesce((item ->> 'is_published')::boolean, p.is_published)
       where p.id = prod_id;
      actualizados := actualizados + 1;
    end if;

    -- precios: la planilla manda
    delete from public.product_variants v where v.product_id = prod_id;
    for variant in select * from jsonb_array_elements(coalesce(item -> 'variants', '[]'::jsonb))
    loop
      insert into public.product_variants (product_id, label, servings, price_cents, sort_order)
      values (
        prod_id,
        variant ->> 'label',
        nullif(variant ->> 'servings', '')::integer,
        (variant ->> 'price_cents')::bigint,
        variantes
      );
      variantes := variantes + 1;
    end loop;

    -- foto de portada (opcional)
    if coalesce(item ->> 'cover_path', '') <> '' then
      update public.product_images i set is_cover = false
        where i.product_id = prod_id and i.is_cover and i.storage_path <> item ->> 'cover_path';
      if exists (
        select 1 from public.product_images i
        where i.product_id = prod_id and i.storage_path = item ->> 'cover_path'
      ) then
        update public.product_images i set is_cover = true
          where i.product_id = prod_id and i.storage_path = item ->> 'cover_path';
      else
        insert into public.product_images (product_id, storage_path, alt_text, is_cover)
        values (prod_id, item ->> 'cover_path', left(item ->> 'name', 200), true);
      end if;
    end if;
  end loop;

  return jsonb_build_object('creados', creados, 'actualizados', actualizados, 'variantes', variantes);
end;
$$;
